def clean(t):
    t = re.sub(r'<table>.*?</table>', '', t, flags=re.S)
    t = re.sub(r'<[^>]+>', ' ', t)
    t = t.replace('&nbsp;', ' ').replace('&amp;', 'и').replace('&quot;', '"')
    t = re.sub(r'_([^_]+)_', r'\1', t)
    t = t.replace('**', '')
    return re.sub(r'\s+', ' ', t).strip()


def head_type(meta):
    depth, buf = 0, []
    for ch in meta:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth = max(0, depth - 1)
        elif ch == ',' and depth == 0:
            break
        buf.append(ch)
    head = ''.join(buf).strip()
    if 'Shield' in head:
        return 'щит'
    base = head.split('(')[0].strip()
    return TYPES.get(base, base.lower())


def shorten(t, limit=340):
    if len(t) <= limit:
        return t
    cut = t[:limit]
    dot = max(cut.rfind('. '), cut.rfind('; '))
    if dot > limit * 0.5:
        return cut[:dot + 1].strip()
    return cut.rsplit(' ', 1)[0].rstrip(' ,;') + '…'


def parse(md):
    out = []
    for block in re.split(r'^#### ', md, flags=re.M)[1:]:
        name = block.split('\n', 1)[0].strip()
        meta = re.search(r'^_(.+?)_\s*$', block, flags=re.M)
        if not meta:
            continue                      # служебные разделы правил
        raw_meta = meta.group(1).strip()
        body = clean(block[meta.end():])
        att = 'Requires Attunement' in raw_meta
        creature = body.startswith('AC ')

        if creature:
            type_ru, rarity_ru = 'существо', '—'
        else:
            type_ru = head_type(raw_meta)
            found = sorted(set(re.findall(r'\b(Very Rare|Uncommon|Common|Rare|Legendary|Artifact)\b', raw_meta)))
            if 'Rarity Varies' in raw_meta or len(found) > 1:
                rarity_ru = 'варьируется'
            elif found:
                rarity_ru = RARITY[found[0]]
            else:
                rarity_ru = '—'
        out.append({
            'name': name, 'type': type_ru, 'rarity': rarity_ru,
            'att': att, 'body': shorten(body),
        })
    return out


def main():
    src = SRC.read_text(encoding='utf-8')
    items = parse(src)

    old_text = OUT.read_text(encoding='utf-8')
    old_data = json.loads(re.search(r'window\.SRD_ITEMS = (\{.*\});', old_text, re.S).group(1))
    old = {i['en']: i for i in old_data['items']}

    result, reused, made = [], 0, 0
    for it in items:
        en = it['name']
        if en in OVERRIDES:
            ru_name, ru_desc = OVERRIDES[en]
            made += 1
        elif en in old and old[en].get('d'):
            ru_name, ru_desc = old[en]['n'], clean(old[en]['d'])
            reused += 1
        else:
            print('НЕТ ПЕРЕВОДА:', en)
            ru_name, ru_desc = en, it['body']
            made += 1
        result.append({
            'n': ru_name, 'en': en, 'rarity': it['rarity'],
            'att': it['att'], 'type': it['type'], 'd': ru_desc,
        })

    header = (
        '// Магические предметы SRD 5.2.1 (System Reference Document), лицензия CC-BY-4.0.\n'
        '// Источник: data/srd521/magic-items.md. Краткие описания сжаты до 1–2 предложений.\n'
        '// Сгенерировано _build_srd_items_521.py.\n'
    )
    payload = {'source': 'SRD 5.2.1 (CC-BY-4.0)', 'items': result}
    OUT.write_text(header + 'window.SRD_ITEMS = ' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n',
                   encoding='utf-8')

    print('предметов:', len(result), '| переиспользовано описаний:', reused, '| новых/переименованных:', made)
    latin = [i['n'] for i in result if re.search(r'[A-Za-z]{3,}', i['n'])]
    print('названий с латиницей:', len(latin), latin[:5])
    return 0


if __name__ == '__main__':
    sys.exit(main())
